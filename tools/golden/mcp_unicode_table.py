"""Writes crates/grainy-mcp/src/printable.rs: the code points Python's str.isprintable() rejects (exact Unicode
tables of the oracle's interpreter), as sorted inclusive ranges. Run with the oracle's interpreter."""
import sys
import unicodedata
from pathlib import Path

ranges = []
start = None
for code in range(0x110000):
    bad = not chr(code).isprintable()
    if bad and start is None:
        start = code
    if not bad and start is not None:
        ranges.append((start, code - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

out = Path(__file__).resolve().parents[2] / 'crates' / 'grainy-mcp' / 'src' / 'printable.rs'
lines = ['//! Generated by tools/golden/mcp_unicode_table.py: the code points Python\'s `str.isprintable()` rejects',
         f'//! (Unicode {unicodedata.unidata_version}, Python {sys.version.split()[0]}), as sorted inclusive ranges.', '',
         '/// Whether `str.isprintable()` is true for the character.',
         'pub fn is_printable(c: char) -> bool {',
         '    let n = c as u32;',
         '    RANGES.binary_search_by(|&(low, high)| if n < low { std::cmp.Ordering::Greater } else if n > high { std::cmp::Ordering::Less } else { std::cmp::Ordering::Equal }).is_err()'.replace('std::cmp.Ordering', 'std::cmp::Ordering'),
         '}', '', f'const RANGES: [(u32, u32); {len(ranges)}] = [']
row = '   '
for low, high in ranges:
    item = f' (0x{low:x}, 0x{high:x}),'
    if len(row) + len(item) > 118:
        lines.append(row)
        row = '   '
    row += item
lines.append(row)
lines.append('];')
out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print(len(ranges), 'ranges ->', out)
